import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import { enterpriseAnalysis } from './enterprise_v08.mjs';
const raw=enterpriseAnalysis({});
const ctx={window:{},document:{addEventListener:()=>{},body:{append:()=>{}},createElement:()=>({click(){},remove(){},append(){},dataset:{},style:{}}),getElementById:()=>null},console,fetch:async()=>({ok:true,json:async()=>raw}),location:{hash:'#ss-performance'},sessionStorage:{getItem:()=>null,setItem:()=>{}},URL:{createObjectURL:()=>'',revokeObjectURL:()=>{}},render:()=>{}};
ctx.window=ctx;ctx.PharmaGlobalHelp={open:()=>{}};
vm.createContext(ctx);
vm.runInContext(fs.readFileSync('static/strategic_sourcing_universe.js','utf8'),ctx);
