import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import {enterpriseAnalysis} from './enterprise_v08.mjs';
const d=enterpriseAnalysis({});
const js=fs.readFileSync('static/portfolio_strategy.js','utf8');
const listeners=[];
const doc={readyState:'loading',addEventListener:(...args)=>listeners.push(args)};
const W={EnterpriseV08:{state:{data:d,filters:{}}},render:()=>{}};
const sandbox={window:W,document:doc,console,setTimeout,URL,Blob,Intl};
vm.runInNewContext(js,sandbox,{filename:'portfolio_strategy.js'});
const P=W.PharmaPortfolio;
assert(P,'portfolio module loaded');
const model=P.makeModel(d);
assert.equal(model.visibleProducts.length,2,'Top30 must reflect real product count, not invent 30 rows');
assert.equal(model.allOrders.length,24);
assert.equal(model.spend,d.base.metrics.spend,'must reconcile with shared Overview spend');
assert.equal(Math.round(model.otd*10)/10,91.7,'must reconcile with shared OTD');
assert.equal(model.selectedQuality.length,d.supplier.quality_events.length);
assert.equal(model.events.every(e=>e.row&&e.date>=model.asOf&&e.date<=model.end),true,'no invented calendar dates');
assert.equal(model.events.some(e=>e.type==='contract'),true,'contracts must flow from source register');
assert.equal(model.events.some(e=>e.type==='doc'),true,'qualification documents must flow from source register');
assert.equal(model.actionRows.every(x=>x.evidence&&x.evidence.length),true);
assert.equal(model.materials.reduce((a,x)=>a+x.spend,0),model.spend,'ABC must tie to scoped PO total');
assert.equal(P.render().includes('预算执行率'),true);
assert.equal(P.render().includes('未接入'),true,'missing budget must not be fabricated');
P.state.selected='DRUG-A';
const a=P.makeModel(d);
assert.equal(a.selectedProducts.length,1);
assert.equal(a.spend,d.purchasing.orders.filter(x=>x.material_id==='API-001').reduce((t,x)=>t+Number(x.amount||0),0));
assert.equal(a.selectedLots.every(x=>x.material_id==='API-001'),true);
P.state.selected='';P.state.market='JP';
assert.deepEqual(Array.from(P.makeModel(d).visibleProducts.map(p=>p.id)),['DRUG-B']);
P.state.market='all';P.state.range='top10';assert.equal(P.makeModel(d).visibleProducts.length,2);
P.state.range='top30';P.state.risk='LOW';const low=P.makeModel(d);assert.equal(low.visibleProducts.every(p=>p.risk==='LOW'),true);
assert.equal(fs.readFileSync('static/app.js','utf8').includes('data-nav="portfolio"'),true,'new sidebar entry must exist');
assert.equal(fs.readFileSync('static/app.js','utf8').includes("S.view==='portfolio'"),true,'route integration required');
assert.equal(fs.readFileSync('static/index.html','utf8').includes('data-bundled-src="/static/portfolio_strategy.js"'),true);
console.log('PASS V2.2: actual product scope, 24 PO spend/OTD, ABC reconciliation, contract/document calendar, source actions, segment selection and original navigation.');
