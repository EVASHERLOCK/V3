/* V2.1 M01 data contract tests — real PO/production/lot linked model, no fabricated forecast accuracy. */
import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import {enterpriseAnalysis} from './enterprise_v08.mjs';
const script=fs.readFileSync('static/m01_planning.js','utf8');
const fakeDocument={readyState:'loading',addEventListener:()=>{},getElementById:()=>null};
const enterprise={state:{data:enterpriseAnalysis({}),filters:{},active:'overview',loading:false}};
const context={window:{EnterpriseV08:enterprise},document:fakeDocument,console,setTimeout,clearTimeout};
vm.runInNewContext(script,context,{filename:'m01_planning.js'});
const api=context.window.PharmaM01;
assert(api&&api.render&&api.model);
const model=api.model(enterprise.state.data);
assert.equal(model.prod.length,12);assert.equal(model.gaps.length,7);
assert.equal(model.gaps.filter(x=>x.priority==='HIGH').length,3);
assert.equal(Number(model.ready),41.7);
assert.equal(model.lots.length,12);
assert.equal(model.riskAmount,model.gaps.reduce((sum,x)=>sum+Number(x.impact_amount||0),0));
assert.equal(model.pareto.reduce((a,x)=>a+x.count,0),model.gaps.length);
assert.equal(Math.round(model.pareto.at(-1).cumulative),100);
assert.equal(model.mat.reduce((a,x)=>a+x.riskCount,0),model.gaps.length);
assert(!model.months.some(x=>x.period.startsWith('2025')));
let html=api.render();
for(let label of ['需求与物料计划','月度物料需求 vs 当前可用库存','缺料物料 TOP10','数量偏差 TOP10','库存覆盖天数分布','物料风险分类占比','预警汇总','误差根因追溯矩阵','偏差根因追溯矩阵','未接入'])assert(html.includes(label),label);
assert.equal((html.match(/class="m01-kpi /g)||[]).length,6);
assert.equal((html.match(/data-m01-tab=/g)||[]).length,5);
enterprise.state.filters={supplier:'SUP-001'};
enterprise.state.data=enterpriseAnalysis(enterprise.state.filters);
const sub=api.model(enterprise.state.data);
assert.equal(sub.prod.length,4);assert.equal(sub.gaps.length,1);assert.equal(Number(sub.ready),75);
assert.equal(sub.mat.reduce((a,x)=>a+x.riskCount,0),1);
enterprise.state.filters={month:'2026-07'};
enterprise.state.data=enterpriseAnalysis(enterprise.state.filters);
assert.equal(api.model(enterprise.state.data).prod.length,10);
enterprise.state.filters={material:'API-001'};
enterprise.state.data=enterpriseAnalysis(enterprise.state.filters);
assert.equal(api.model(enterprise.state.data).prod.length,8);
assert(!script.includes('94%｜目标'));assert(script.includes('正式预测准确率'));
console.log('PASS V2.1: 6 evidence-derived KPIs, source-backed trace matrix, 5 detail tabs, 7 actual risks / 3 HIGH, retained Pareto math, supplier/month/material filter math, explicit missing forecast basis');
