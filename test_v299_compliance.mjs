import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
import {enterpriseAnalysis} from './enterprise_v08.mjs';
const raw=enterpriseAnalysis({});
const storage={};const window={};const document={addEventListener() {}};
const ctx={window,document,location:{hash:'#ss-compliance'},sessionStorage:{getItem:k=>storage[k]||null,setItem:(k,v)=>storage[k]=v},console,Date,Math,Intl,setTimeout};vm.createContext(ctx);
for(const file of ['static/strategic_sourcing_compliance.js'])vm.runInContext(fs.readFileSync(file,'utf8'),ctx,{filename:file});
const api=window.PharmaSourcingCompliance;
assert.equal(api?.version,'2.9.9');
assert.equal(typeof api.build,'function');
const m=api.build(raw);
assert.equal(m.documents.length,18,'18 controlled source documents');
assert.equal(m.origin.length,18);
assert.equal(m.validity,12,'12 valid records');
assert.equal(m.docCoverage,12/18*100);
assert.equal(m.qualification.length,6,'6 site-material source combinations');
assert.equal(m.qualifiedCount,2,'only 2 demo-qualified combinations');
assert.equal(m.bins.find(x=>x.key==='expired').items.length,2,'expired documents');
assert.equal(m.bins.find(x=>x.key==='30').items.length,3,'30-day expiry count');
assert.equal(m.documents.filter(x=>x.days_to_expiry>=0&&x.days_to_expiry<=90).length,5,'90-day expiry');
assert.equal(m.allGaps.length,3,'source-only 3 document gaps');
assert.equal(m.tasks.length,5,'3 gaps plus 2 open audit follow-ups');
assert.equal(m.supplierCount,2,'2 suppliers with demo-qualified combinations');
assert.equal(m.origin.filter(x=>x.status==='Under review').length,4);
const s2=api.build(raw,{supplier:'SUP-002'});assert.equal(s2.documents.length,6);assert.equal(s2.qualification.length,2);assert.equal(s2.qualifiedCount,0);
const material=api.build(raw,{material:'API-002'});assert.equal(material.documents.length,9);assert.equal(material.qualification.length,3);assert.equal(material.qualifiedCount,1);
const exp=api.build(raw,{period:'expired'});assert.equal(exp.documents.length,2);
const sr=api.build(raw,{supplier:'SUP-001',material:'API-001'});assert(sr.qualification.every(x=>x.supplier_id==='SUP-001'&&x.material_id==='API-001'));
const local=[{doc_id:'LOCAL-001',supplier_id:'SUP-001',site_id:'SITE-001',material_id:'API-001',market:'US',type:'CEP',version:'X000',expiry:'2027-11-01',status:'Valid'}];
const simulated=api.build(raw,{},local);assert.equal(simulated.documents.length,19);assert.equal(simulated.qualifiedCount,2,'local data must not grant formal qualification');assert.equal(simulated.validity,12,'local data must not masquerade as current approved certificate');assert.equal(simulated.documents.find(x=>x.doc_id==='LOCAL-001').status,'Unverified');
for(const resource of api.official){assert(resource.url.startsWith('https://'));assert(!resource.url.includes('example.com'));}
const html=fs.readFileSync('static/index.html','utf8');const app=fs.readFileSync('static/app.js','utf8'),help=fs.readFileSync('static/global_help.js','utf8');
assert(app.includes("cn:'供应商合规管理'"));assert(app.includes('window.PharmaSourcingCompliance.render()'));
assert(html.includes('/static/strategic_sourcing_compliance.css'));assert(html.includes('PharmaSourcingCompliance'));assert(help.includes('supplierCompliance')&&help.includes('officialEvidence')&&help.includes('complianceLedger')&&help.includes('complianceRemediation'));
assert.equal(raw.purchasing.orders.length,24);assert.equal(raw.master.suppliers.length,3);
console.log('PASS V2.9.9 Supplier Compliance: 18 docs / 12 valid / 4 review / 2 expired, 6 source combos / 2 demo-qualified, 3 gaps, 5 tasks, full route, external official sources, filters, local-only records, permanent help.');
